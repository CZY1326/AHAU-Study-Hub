const DIFF_BADGE = { '🔥 难': '🔥 难', '⚠️ 中': '⚠️ 中', '✅ 易': '✅ 易' }

function render(sem) {
  const courseRows = sem.courses
    .map(([name, desc, diff]) => `| [${name}](./${name}/) | ${desc} | ${DIFF_BADGE[diff] ?? diff} |`)
    .join('\n')

  const strategyLines = sem.strategies.map((s, i) => `${i + 1}. ${s}`).join('\n')

  const jumpLinks = sem.courses.map(([name]) => `- [${name}](./${name}/)`).join('\n')

  return `# ${sem.icon} ${sem.dir.replace(/^\d{2}-/, '')}

> ${sem.intro}

## 📚 课程一览

| 课程 | 内容与难点 | 难度 |
| :--- | :--- | :---: |
${courseRows}

## 💡 学期总攻略

::: tip 这一学期怎么过
${strategyLines}
:::

## 🔗 快速跳转

${jumpLinks}

---

::: info 资料状态
本页课程资料正在陆续补充。**课件 / 试卷与答案 / 复习资料** 三个子目录已建好，
欢迎把手上有的资料提 PR 补进来 —— 尤其是历年真题，价值最高。
:::
`
}

async function main() {
  let updated = 0
  for (const sem of SEMESTERS) {
    const file = join(DOCS, sem.dir, 'index.md')
    await writeFile(file, render(sem), 'utf8')
    updated++
  }
  console.log(`✅ 已更新 ${updated} 个学期页面。`)
}

main().catch((e) => {
  console.error('❌ enrich 失败：', e)
  process.exit(1)
})
