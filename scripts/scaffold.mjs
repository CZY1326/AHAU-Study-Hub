/**
 * 把模块的主题清单表注入模块 index.md 的 TOPICS 标记区间。
 * 没有标记区间时，自动在文末追加整段（含标记），保证幂等。
 */
async function injectTopicsTable(indexFile, moduleTitle, topics) {
  const rows = topics
    .map(([dir, title]) => {
      // 目录名含括号/空格等字符时，Markdown 链接目标必须用尖括号包裹，否则解析会断
      const dest = /[()\s<>]/.test(dir) ? `<./${dir}/>` : `./${dir}/`
      return `| [${title}](${dest}) |`
    })
    .join('\n')
  const table = `## 本模块主题\n\n| 主题 |\n| :--- |\n${rows}\n`
  const block = `${TOPICS_START}\n${table}${TOPICS_END}`

  let md = ''
  try {
    md = await readFile(indexFile, 'utf8')
  } catch {
    return false // 模块页不存在就跳过（理论上 scaffold 已先生成）
  }

  const re = new RegExp(`${TOPICS_START}[\\s\\S]*?${TOPICS_END}`)
  const updated = re.test(md) ? md.replace(re, block) : `${md.trimEnd()}\n\n---\n\n${block}\n`
  if (updated === md) return false
  await writeFile(indexFile, updated, 'utf8')
  return true
}

/* ------------------------------------------------------------------ *
 * 执行
 * ------------------------------------------------------------------ */

async function main() {
  await ensureDir(DOCS)

  for (const mod of MODULES) {
    const modDir = join(DOCS, mod.dir)
    await ensureDir(modDir)

    const conf = COURSE_GROUPS[mod.dir]

    // 模块 index
    let moduleTpl
    if (conf?.kind === 'semester') moduleTpl = courseModuleIndex(mod, conf.groups)
    else if (conf?.kind === 'elective') moduleTpl = electiveModuleIndex(mod, conf.groups)
    else moduleTpl = moduleIndex(mod)
    if (await emit(join(modDir, 'index.md'), moduleTpl)) written.push(`${mod.dir}/index.md`)

    // 课程模块：分组（学期/公选分类）→ 课程
    if (conf) {
      for (const [groupName, courses] of conf.groups) {
        const groupDir = join(modDir, groupName)
        await ensureDir(groupDir)
        const isInfo = groupName === INFO_GROUP
        if (await emit(join(groupDir, 'index.md'), groupIndex(groupName, courses, isInfo))) {
          written.push(`${mod.dir}/${groupName}/index.md`)
        }
        for (const [courseName] of courses) {
          const courseDir = join(groupDir, courseName)
          await ensureDir(courseDir)
          for (const sub of COURSE_SUBDIRS) {
            await ensureDir(join(courseDir, sub))
            const keep = join(courseDir, sub, '.gitkeep')
            if (!(await exists(keep))) {
              await writeFile(keep, '', 'utf8')
              written.push(`${mod.dir}/${groupName}/${courseName}/${sub}/.gitkeep`)
            }
          }
          const tpl = isInfo
            ? infoIndex(courseName, groupName)
            : courseIndex(courseName, groupName.slice(3) || groupName)
          if (await emit(join(courseDir, 'index.md'), tpl)) {
            written.push(`${mod.dir}/${groupName}/${courseName}/index.md`)
          }
        }
      }
    }

    // 主题模块：为每个主题建目录 + 文章 index.md（无资料子目录），
    // 并把主题清单表注入模块 index.md 的 TOPICS 标记区间。
    const topics = TOPICS[mod.dir]
    if (topics) {
      for (const [dir, title] of topics) {
        const topicDir = join(modDir, dir)
        await ensureDir(topicDir)
        if (await emit(join(topicDir, 'index.md'), topicIndex(title, mod.title))) {
          written.push(`${mod.dir}/${dir}/index.md`)
        }
      }
      if (await injectTopicsTable(join(modDir, 'index.md'), mod.title, topics)) {
        written.push(`${mod.dir}/index.md（主题表）`)
      }
    }
  }

  console.log(`✅ 骨架生成完毕，共写入 ${written.length} 个文件。`)
  if (FORCE) console.log('   （--force 模式：已覆盖既有模板）')
}

main().catch((err) => {
  console.error('❌ scaffold 失败：', err)
  process.exit(1)
})
