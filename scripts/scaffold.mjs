/** 02-课程资料 模块页：学期总览 */
function courseModuleIndex(mod, groups) {
  const rows = groups
    .map(([name, courses]) => `| [${name.slice(3)}](./${name}/) | ${courses.length} |`)
    .join('\n')
  return `# ${mod.title}

> ${mod.blurb}

## 学期一览

| 学期 | 课程数 |
| :--- | :---: |
${rows}
`
}

/** 05-公选课外 模块页：分组总览 */
function electiveModuleIndex(mod, groups) {
  const desc = { 校本公选: '全校开放的公选、通识与公共课', 园艺专选: '专业选修与配套实验/实习', 其他课程: '公共基础与跨专业课程', 课外资料: '工具平台、事务指南与兴趣资料' }
  const rows = groups
    .map(([name]) => `| [${name}](./${name}/) | ${desc[name] || ''} |`)
    .join('\n')
  return `# ${mod.title}

> ${mod.blurb}

## 课程分组

| 分组 | 说明 |
| :--- | :--- |
${rows}
`
}

